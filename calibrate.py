#!/usr/bin/env python3
"""
Interactive Calibration Tool

Guides the user through setting up button coordinates for the screen recorder app.
Saves the configuration to .env file.

Usage:
    python calibrate.py
"""

import sys
import time
from pathlib import Path
from typing import Tuple, Optional

try:
    import pyautogui
    from pynput import keyboard
except ImportError:
    print("Error: Required packages not installed.")
    print("Run: pip install pyautogui pynput")
    sys.exit(1)


class Calibrator:
    """Interactive calibration tool for button position setup."""
    
    def __init__(self):
        self.start_button_pos: Optional[Tuple[int, int]] = None
        self.stop_button_pos: Optional[Tuple[int, int]] = None
        self.recorder_title: str = ""
        self.browser_title: str = ""
        self.current_action: str = ""
        self.listener: Optional[keyboard.Listener] = None
        
    def on_key_press(self, key):
        """Handle keyboard events during calibration."""
        try:
            # Start button capture
            if hasattr(key, 'char') and key.char == 's' and self.current_action == "start":
                self.start_button_pos = pyautogui.position()
                print(f"✓ START button position saved: {self.start_button_pos}")
                return False  # Stop listener
            
            # Stop button capture
            elif hasattr(key, 'char') and key.char == 'p' and self.current_action == "stop":
                self.stop_button_pos = pyautogui.position()
                print(f"✓ STOP button position saved: {self.stop_button_pos}")
                return False  # Stop listener
            
            # Cancel
            elif key == keyboard.Key.esc:
                print("\n[!] Calibration cancelled by user")
                return False
                
        except AttributeError:
            pass
    
    def capture_position(self, button_name: str, key_to_press: str) -> Optional[Tuple[int, int]]:
        """Capture cursor position when user presses specified key."""
        print(f"\n→ Move your cursor to the {button_name} button")
        print(f"  Press '{key_to_press}' when positioned correctly")
        print(f"  Press 'ESC' to cancel")
        
        self.current_action = button_name.lower().split()[0]
        
        # Start keyboard listener
        with keyboard.Listener(on_press=self.on_key_press) as self.listener:
            self.listener.join()
        
        return self.start_button_pos if button_name == "START" else self.stop_button_pos
    
    def get_window_titles(self) -> Tuple[str, str]:
        """Get window titles from user."""
        print("\n" + "=" * 60)
        print("WINDOW CONFIGURATION")
        print("=" * 60)
        
        print("\n→ What is the window title of your screen recorder?")
        print("  Examples: 'OBS Studio', 'ScreenFlow', 'Camtasia Recorder'")
        recorder = input("  Recorder window title: ").strip()
        
        print("\n→ What is the window title of your browser?")
        print("  Examples: 'YouTube - Mozilla Firefox', 'YouTube - Google Chrome'")
        browser = input("  Browser window title: ").strip()
        
        return recorder, browser
    
    def save_to_env(self):
        """Save calibration data to .env file."""
        env_path = Path(__file__).parent / ".env"
        
        env_content = f"""# Screen Recorder Automation Bot - Environment Configuration
# Generated by calibrate.py on {time.strftime('%Y-%m-%d %H:%M:%S')}

# Window Identifiers
RECORDER_APP_TITLE={self.recorder_title}
BROWSER_WINDOW_TITLE={self.browser_title}

# Button Coordinates
START_BUTTON_X={self.start_button_pos[0]}
START_BUTTON_Y={self.start_button_pos[1]}
STOP_BUTTON_X={self.stop_button_pos[0]}
STOP_BUTTON_Y={self.stop_button_pos[1]}

# Display Settings (auto-detected)
SCREEN_WIDTH={pyautogui.size().width}
SCREEN_HEIGHT={pyautogui.size().height}
DPI_SCALE=1.0
"""
        
        # Backup existing .env if it exists
        if env_path.exists():
            backup_path = env_path.with_suffix('.env.backup')
            env_path.rename(backup_path)
            print(f"\n[i] Existing .env backed up to: {backup_path.name}")
        
        # Write new .env
        env_path.write_text(env_content)
        print(f"✓ Configuration saved to: {env_path}")
    
    def verify_calibration(self) -> bool:
        """Show preview and ask for confirmation."""
        print("\n" + "=" * 60)
        print("CALIBRATION SUMMARY")
        print("=" * 60)
        print(f"Recorder App:   {self.recorder_title}")
        print(f"Browser:        {self.browser_title}")
        print(f"START button:   X={self.start_button_pos[0]}, Y={self.start_button_pos[1]}")
        print(f"STOP button:    X={self.stop_button_pos[0]}, Y={self.stop_button_pos[1]}")
        print(f"Screen size:    {pyautogui.size().width}x{pyautogui.size().height}")
        print("=" * 60)
        
        response = input("\n→ Does this look correct? (y/n): ").strip().lower()
        return response == 'y'
    
    def run(self):
        """Execute calibration workflow."""
        print("=" * 60)
        print("SCREEN RECORDER BOT - CALIBRATION TOOL")
        print("=" * 60)
        print("\nThis tool will help you set up the bot for your system.")
        print("You'll need to identify button positions and window titles.")
        
        # Get window titles
        self.recorder_title, self.browser_title = self.get_window_titles()
        
        # Capture button positions
        print("\n" + "=" * 60)
        print("BUTTON POSITION CALIBRATION")
        print("=" * 60)
        print("\n[!] Make sure your screen recorder app is visible on screen")
        input("    Press ENTER when ready...")
        
        # START button
        self.start_button_pos = self.capture_position("START", "S")
        if not self.start_button_pos:
            print("\n[!] Calibration cancelled")
            return 1
        
        time.sleep(0.5)
        
        # STOP button
        self.stop_button_pos = self.capture_position("STOP", "P")
        if not self.stop_button_pos:
            print("\n[!] Calibration cancelled")
            return 1
        
        # Verify and save
        if self.verify_calibration():
            self.save_to_env()
            
            print("\n" + "=" * 60)
            print("✓ CALIBRATION COMPLETE!")
            print("=" * 60)
            print("\nNext steps:")
            print("  1. Review config.yaml to adjust behavior settings")
            print("  2. Run a test: python main.py --dry-run")
            print("  3. Start production: python main.py")
            
            return 0
        else:
            print("\n[!] Calibration discarded. Run again to retry.")
            return 1


def main():
    """Main entry point."""
    try:
        calibrator = Calibrator()
        return calibrator.run()
    
    except KeyboardInterrupt:
        print("\n\n[!] Interrupted by user")
        return 130
    
    except Exception as e:
        print(f"\n[!] Error: {e}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
